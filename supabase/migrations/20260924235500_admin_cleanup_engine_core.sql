create table if not exists public.admin_cleanup_settings (
  singleton boolean primary key default true check (singleton),
  config jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

comment on table public.admin_cleanup_settings is
  'Réglages centraux du moteur de tri et de contrôle Admin. Aucune suppression automatique sans décision patron.';

create table if not exists public.admin_cleanup_sources (
  source_key text primary key,
  source_type text not null check (source_type in ('github','supabase_db','supabase_storage','vercel','drive','url')),
  label text not null,
  locator text,
  mode text not null default 'automatic' check (mode in ('automatic','connector_assisted','manual')),
  active boolean not null default true,
  config jsonb not null default '{}'::jsonb,
  last_scan_at timestamptz,
  last_status text,
  last_error text,
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_cleanup_scan_runs (
  id uuid primary key default gen_random_uuid(),
  trigger_kind text not null default 'manual',
  status text not null default 'running' check (status in ('running','completed','completed_with_warnings','failed')),
  scope text[] not null default '{}'::text[],
  summary jsonb not null default '{}'::jsonb,
  error_text text,
  started_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.admin_cleanup_cases (
  id uuid primary key default gen_random_uuid(),
  fingerprint text not null unique,
  evidence_hash text not null,
  source_key text references public.admin_cleanup_sources(source_key) on delete set null,
  category text not null,
  status text not null default 'open'
    check (status in ('open','validated','modify_requested','refused','delete_approved','executing','done','execution_failed','superseded')),
  title text not null,
  question text not null,
  context_text text not null default '',
  facts jsonb not null default '[]'::jsonb,
  metrics jsonb not null default '{}'::jsonb,
  evidence jsonb not null default '[]'::jsonb,
  uncertainties jsonb not null default '[]'::jsonb,
  proposed_action text not null default '',
  proposed_plan jsonb not null default '[]'::jsonb,
  executable_action jsonb,
  evidence_score smallint not null default 0 check (evidence_score between 0 and 100),
  gpt_packet text not null default '',
  gpt_prompts jsonb not null default '[]'::jsonb,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  last_changed_at timestamptz not null default now(),
  decision_kind text check (decision_kind is null or decision_kind in ('validate','modify','refuse','delete')),
  decision_note text,
  decision_at timestamptz,
  decision_by text,
  execution_status text,
  execution_log jsonb not null default '[]'::jsonb,
  result jsonb not null default '{}'::jsonb
);

create index if not exists admin_cleanup_cases_status_idx
  on public.admin_cleanup_cases(status, last_seen_at desc);
create index if not exists admin_cleanup_cases_source_idx
  on public.admin_cleanup_cases(source_key, status);
create index if not exists admin_cleanup_cases_category_idx
  on public.admin_cleanup_cases(category, status);

create table if not exists public.admin_cleanup_case_events (
  id bigint generated by default as identity primary key,
  case_id uuid not null references public.admin_cleanup_cases(id) on delete cascade,
  event_type text not null,
  actor text,
  note text,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists admin_cleanup_case_events_case_idx
  on public.admin_cleanup_case_events(case_id, created_at desc);

