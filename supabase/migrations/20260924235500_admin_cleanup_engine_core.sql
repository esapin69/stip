create or replace function public.admin_cleanup_known_storage_refs()
returns table(source_table text, bucket text, path text)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  r record;
begin
  for r in
    select c.table_name
    from information_schema.columns c
    where c.table_schema='public'
      and c.column_name in ('storage_bucket','storage_path')
    group by c.table_name
    having count(distinct c.column_name)=2
  loop
    return query execute format(
      'select %L::text, storage_bucket::text, storage_path::text
       from public.%I
       where storage_path is not null and btrim(storage_path::text) <> ''''',
      r.table_name,
      r.table_name
    );
  end loop;
end;
$$;

revoke all on function public.admin_cleanup_known_storage_refs() from public, anon, authenticated;

create or replace function public.admin_cleanup_table_inventory()
returns table(
  table_name text,
  estimated_rows bigint,
  total_bytes bigint,
  total_size text
)
language sql
security definer
set search_path = public, pg_temp
as $$
  select
    c.relname::text,
    greatest(c.reltuples::bigint,0),
    pg_total_relation_size(c.oid),
    pg_size_pretty(pg_total_relation_size(c.oid))
  from pg_class c
  join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relkind='r'
  order by pg_total_relation_size(c.oid) desc, c.relname;
$$;

revoke all on function public.admin_cleanup_table_inventory() from public, anon, authenticated;
